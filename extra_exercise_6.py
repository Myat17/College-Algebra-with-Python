# rounding
a = 0.006538298335
b = 14588132

# To round the number of decimal places
print(f"round of {a} to 3 decimal places = {round(a, 3)}") # will return six decimal places

# To round a large number instead of a decimal number
print(f"round of {b} to nearest million = {round(b, -6)}") # will return six zeros